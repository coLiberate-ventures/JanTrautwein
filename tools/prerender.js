#!/usr/bin/env node
/*
 * Static prerender for the main-concept React pages.
 *
 * WHY: index/coaching/contact/client-voices/explore ship an empty <div id="root">
 * and render everything with main-concept/app.js. AI crawlers (GPTBot,
 * OAI-SearchBot, ClaudeBot, PerplexityBot) do not run JavaScript, so they saw
 * ~7 words. This script loads each page in headless Chromium, snapshots the
 * markup React produces on its FIRST commit (before effects/animations), and
 * writes it inside #root between PRERENDER markers. app.js mounts with
 * createRoot(), which replaces the snapshot, so humans see exactly what they
 * saw before. No copy is written here: it is the app's own output.
 *
 * Content the app only reveals on click (closed accordion answers, the other
 * client-voice quotes) is captured by clicking in the browser and added with the
 * `hidden` attribute, so it is readable as text but not displayed.
 *
 * RE-RUN WHENEVER main-concept/app.js CHANGES, otherwise the snapshot goes stale:
 *   npm i --prefix /tmp/pw playwright && npx --prefix /tmp/pw playwright install chromium
 *   NODE_PATH=/tmp/pw/node_modules node tools/prerender.js
 */
const { chromium } = require('playwright');
const http = require('http');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PAGES = ['index.html', 'coaching.html', 'contact.html', 'client-voices.html', 'explore.html'];
const START = '<!--PRERENDER:start (generated by tools/prerender.js, do not edit by hand)-->';
const END = '<!--PRERENDER:end-->';
const BLOCK = /<!--PRERENDER:start[\s\S]*?<!--PRERENDER:end-->/;
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.mp4': 'video/mp4', '.json': 'application/json' };

function serve() {
  return new Promise((resolve) => {
    const srv = http.createServer((req, res) => {
      let p = decodeURIComponent(req.url.split('?')[0]);
      if (p.endsWith('/')) p += 'index.html';
      const f = path.join(ROOT, p);
      if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
      let body = fs.readFileSync(f);
      // Render from a clean shell so a previous snapshot never feeds the next one.
      if (f.endsWith('.html')) body = Buffer.from(body.toString().replace(BLOCK, ''));
      res.writeHead(200, { 'content-type': TYPES[path.extname(f)] || 'application/octet-stream' });
      res.end(body);
    }).listen(0, () => resolve(srv));
  });
}

(async () => {
  const srv = await serve();
  const base = `http://localhost:${srv.address().port}/`;
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  await ctx.addInitScript(() => {
    document.addEventListener('DOMContentLoaded', () => {
      const r = document.getElementById('root');
      if (!r) return;
      const mo = new MutationObserver(() => { if (!window.__snap) { window.__snap = r.innerHTML; mo.disconnect(); } });
      mo.observe(r, { childList: true });
    });
  });

  for (const file of PAGES) {
    const page = await ctx.newPage();
    await page.goto(base + file, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => window.__snap);
    await page.waitForTimeout(500);

    const html = await page.evaluate(async () => {
      const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
      const doc = new DOMParser().parseFromString(`<div id="snap">${window.__snap}</div>`, 'text/html');
      const snap = doc.getElementById('snap');
      const live = document.getElementById('root');

      // 1) Accordions: capture what a click reveals inside each collapsed item.
      const liveBtns = [...live.querySelectorAll('article > button[aria-expanded]')];
      const snapBtns = [...snap.querySelectorAll('article > button[aria-expanded]')];
      if (liveBtns.length === snapBtns.length) {
        for (let i = 0; i < liveBtns.length; i++) {
          if (snapBtns[i].getAttribute('aria-expanded') === 'true') continue;
          const art = liveBtns[i].parentElement;
          const before = new Set(art.children);
          liveBtns[i].click();
          await sleep(150);
          for (const el of [...art.children]) {
            if (before.has(el)) continue;
            const c = el.cloneNode(true);
            c.setAttribute('hidden', '');
            c.removeAttribute('style');
            snapBtns[i].parentElement.appendChild(c);
          }
        }
      }

      // 2) Client voices: capture each quote card the portrait buttons switch to.
      const portraits = [...live.querySelectorAll('.voices-page-portraits button')];
      const snapCard = snap.querySelector('article[aria-live]');
      if (portraits.length && snapCard) {
        let anchor = snapCard;
        for (let i = 1; i < portraits.length; i++) {
          portraits[i].click();
          await sleep(150);
          const card = live.querySelector('article[aria-live]').cloneNode(true);
          card.removeAttribute('aria-live');
          card.setAttribute('hidden', '');
          anchor.after(card);
          anchor = card;
        }
      }
      return snap.innerHTML;
    });

    const target = path.join(ROOT, file);
    const src = fs.readFileSync(target, 'utf8').replace(BLOCK, '');
    const m = src.match(/(<div id="root"[^>]*>)(\s*)(<\/div>)/);
    if (!m) throw new Error(`no empty #root in ${file}`);
    const out = src.replace(m[0], `${m[1]}${START}${html}${END}${m[3]}`);
    fs.writeFileSync(target, out);
    const words = html.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
    console.log(`${file}: ${words} words prerendered`);
    await page.close();
  }
  await browser.close();
  srv.close();
})().catch((e) => { console.error(e); process.exit(1); });
